# Provenance ---------------------------------------------------------------
#
# Every generator returns its result through new_dg_dataset(), so the synthetic
# label and the parameter record cannot be left out. The record is stored as
# an attribute, and the class "dg_dataset" makes print() show the banner.

new_dg_dataset <- function(x, generator, params, seed, assumptions) {
  meta <- list(
    synthetic = TRUE,
    generator = generator,
    params = params,
    seed = seed,
    assumptions = assumptions,
    package_version = package_version_string(),
    # Creation time is recorded for provenance. It is not part of the data, so
    # the same seed reproduces the same values even though this differs.
    created = Sys.time()
  )
  as_dg_dataset(x, meta)
}

as_dg_dataset <- function(x, meta) {
  x <- tibble::as_tibble(x)
  attr(x, "dg_meta") <- meta
  class(x) <- c("dg_dataset", setdiff(class(x), "dg_dataset"))
  x
}

strip_dg <- function(x) {
  attr(x, "dg_meta") <- NULL
  class(x) <- setdiff(class(x), "dg_dataset")
  x
}

single_column <- function(values, name) {
  tibble::as_tibble(stats::setNames(list(values), name))
}

package_version_string <- function() {
  tryCatch(
    as.character(utils::packageVersion("datagenerator")),
    error = function(e) NA_character_
  )
}

#' Read the provenance record of a synthetic dataset
#'
#' @param x A dataset returned by a datagenerator function.
#'
#' @return A named list with the generator name, its parameters, the seed,
#'   the assumptions it encodes, the package version, and the creation time.
#'   `synthetic` is always `TRUE`.
#' @export
#' @examples
#' x <- gen_numeric(n = 3, mean = 5, seed = 42)
#' dg_meta(x)$params
dg_meta <- function(x) {
  if (!inherits(x, "dg_dataset")) {
    cli::cli_abort(c(
      "{.arg x} must be a dataset made by a datagenerator function.",
      "i" = "It has class {.cls {class(x)[1]}}."
    ))
  }
  attr(x, "dg_meta")
}

#' Print a synthetic dataset with a banner
#'
#' Prints a warning line naming the generator and seed, then the tibble.
#'
#' @param x A `dg_dataset`.
#' @param ... Passed to [print.tbl_df()].
#' @return `x`, invisibly.
#' @export
print.dg_dataset <- function(x, ...) {
  meta <- dg_meta(x)
  cat("-- SYNTHETIC DATA: generated by datagenerator, not real observations --\n")
  cat("-- generator: ", meta$generator, " | seed: ", meta$seed, "\n", sep = "")
  print(strip_dg(x), ...)
  invisible(x)
}
